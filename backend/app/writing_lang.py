"""写作语言：项目产出物用中文还是英文撰写。

**这个模块只管语言本身，不管参考文献格式** —— 哪种语言能用哪种著录格式是
`app.citation_format` 的知识（它 import 本模块拿 DEFAULT_LANG，反向不 import，
免得绕成一个环）。

## 一条必须画清的线：界面文案 vs 产出物

「选中文/英文」**只决定产出物的语言**（论文标题、摘要、关键词、正文、参考文献），
**不决定界面文案的语言** —— 界面、类型名、工序名、设计字段名一律仍是中文。这条是
用户明确拍板的，别顺手把界面英文化了，那会让「同一份提示词在 zh 路径下逐字节不变」
这条保证（也就是 `tests/test_outline_agent.py` 里那一批按中文串分发的用例）一起失效。

于是本模块的判据可以一句话说清：**会变成论文里一行字的东西跟随语言，只是给模型看的
指令或给用户看的文案不跟随。** 骨架的章/节标题、两条类型说明属于前者；提示词里的
角色设定、说明文字属于后者。

## 为什么指令语言与产物语言可以分开

提示词一律保持中文（只有 `output_rule` 追加一条显式的输出语言宣告）。模型既能读中文
指令，也能用英文写正文 —— 这两件事本来就不相干。而把提示词整体英文化的代价是实打实的：
`tests/test_outline_agent.py` 的 `_stub_llm` 按中文串「篇幅规划专家」分发提示词，
首行一改，那个文件里约四十个用例会同时走错分支。
"""
from __future__ import annotations

from typing import Any

# 界面上的顺序就是这里的顺序
SUPPORTED_LANGS = ["zh", "en"]
# 界面文案**仍是中文**（见模块 docstring）
LANG_LABELS = {"zh": "中文", "en": "英文"}
# 存量项目全部落在 zh 上（DB 列的 DEFAULT 也是它）
DEFAULT_LANG = "zh"


def normalize(lang: Any) -> str:
    """把任意输入收敛到支持的语种，未知值一律回落中文。

    用于**读取侧**：`writing_lang` 可能来自旧库的空值、手改的库里的一段脏字符串，
    也可能是将来某天被删掉的语种。渲染与提示词不该因为一个语种字段坏掉而整段失败，
    所以这里永不抛异常。
    """
    text = str(lang or "").strip().lower()
    return text if text in SUPPORTED_LANGS else DEFAULT_LANG


def is_en(lang: Any) -> bool:
    return normalize(lang) == "en"


def words_unit(lang: Any) -> str:
    """目标字数的计数单位。

    中文按**字符**、英文按**词** —— 这不只是显示问题：`generate_agent.count_units`
    用同一个判据决定正文长度怎么数，两处必须同源。界面上不显示单位的话，用户会给一篇
    英文论文填「5000 字」，而实际产出 5000 个词（约等于中文七千多字的体量）。
    """
    return "words" if is_en(lang) else "字"


def cap_chars(lang: Any, zh_chars: int) -> int:
    """中文里的一个字符上限，在英文里的等值上限。

    模型输出里有两处按**字符**截断：大纲的论文标题（60 字）与核心问题（100 字）。
    这对中文是合理的，对英文则会把一个正常的论文标题**截断在词中间**（60 个字符
    大约只有十个英文词，而英文标题常在十到十五词）。英文按三倍放宽：这个数只用来
    兜住模型的失控输出，不是目标长度，宽一点没有代价。
    """
    return zh_chars * 3 if is_en(lang) else zh_chars


def output_rule(lang: Any) -> str:
    """给提示词追加的「输出语言」宣告；**中文返回空串**。

    返回空串是本模块最要紧的一行约定：中文路径下全部提示词因此**逐字节不变**，
    既有的中文提示词断言与 `_stub_llm` 的中文分发都继续成立。英文路径下也只加这一段，
    其余指令语言不动（见模块 docstring）。

    宣告里写明「JSON 里各字段的取值」也跟着变：接它的几个提示词（选题、聚类、设计
    提炼、材料分析）产出的都是结构化字段，其中一部分会成为论文里的一行字（选题标题、
    主题维度名、设计取值、材料要点），只写「各级标题、摘要、正文段落」管不到它们。

    末句点明「文献题名与作者姓名可保留原文」：中文文献在英文论文的参考文献列表里
    题名是要保留的（APA 7 的方括号英译另说，那是著录格式的事），不写这一句模型会把
    原文题名也一起翻译掉。
    """
    if not is_en(lang):
        return ""
    return (
        "\n\n**输出语言**：你这次产出的**全部文字**都必须用**英文**撰写 —— 包括各级"
        "标题、摘要、正文段落，以及 JSON 里各字段的**取值**；不要输出任何中文字符。"
        "文献题名与作者姓名可以保留原文。"
    )
